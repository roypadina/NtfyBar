#!/usr/bin/env python3
"""Regenerates Sources/NtfyBarCore/Util/EmojiData.swift from ntfy's tag→emoji map.

Source: https://github.com/binwiederhier/ntfy/blob/main/mail/mailer_emoji_map.json
(ntfy, Apache-2.0; the shortcodes come from GitHub's gemoji, MIT).
Usage: Scripts/gen_emoji.py path/to/mailer_emoji_map.json"""
import json
import os
import sys

src = json.load(open(sys.argv[1], encoding="utf-8"))
lines = []
for code in sorted(src):
    emoji = src[code]
    if "\t" in code or "\n" in code or '"""' in code or "\\" in code or "\\" in emoji:
        continue
    lines.append(f"{code}\t{emoji}")
out = os.path.join(os.path.dirname(__file__), "..", "Sources", "NtfyBarCore", "Util", "EmojiData.swift")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by Scripts/gen_emoji.py — do not edit.\n")
    f.write("// ntfy tag shortcodes → emoji, from ntfy (Apache-2.0, github.com/binwiederhier/ntfy),\n")
    f.write("// whose shortcodes come from GitHub gemoji (MIT, github.com/github/gemoji).\n\n")
    f.write("enum EmojiData {\n    static let table = \"\"\"\n")
    for line in lines:
        f.write("        " + line + "\n")
    f.write("        \"\"\"\n}\n")
print(f"{len(lines)} emoji")
